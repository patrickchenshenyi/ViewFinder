#!/usr/bin/env python3
"""M6.6.1: VLM 提示词（共享）——「3DGS 取景模拟器」视角。

核心四点（plan_m6.md §15.6）：
  ① 预览声明：3DGS 渲染可能有空洞/黑边/雾/撕裂/糊，真实拍摄不存在 → 必须全部忽略；
  ② 视点级判断：站在这个相机位置用真实相机拍，会不会是一张好照片；
  ③ 允许非公式化：有意倾斜 / 大留白 / 非常规取景 / 环境交代 / 氛围都可以是好的；
  ④ 理由基于真实照片里会出现的东西，禁止基于渲染画质。

vlm_score.py 用 SELECT_PROMPT_TMPL，refine.py 用 INTENT_PROMPT。
"""

PREAMBLE = (
    "背景：以下图片是 3DGS 三维重建的**预览渲染**（相当于「取景模拟器」）。"
    "渲染可能有大面积空洞、黑边、雾、撕裂、模糊等**重建缺陷**——"
    "这些缺陷在真实拍摄时完全不存在，请**全部忽略**，不要因它们扣分，也不要提及它们。\n"
    "任务：判断**如果摄影师站在这台相机的位置、用真实相机拍下这个场景，会不会是一张好照片**。\n"
    "注意：好照片**不限于**经典构图——有意的倾斜、大面积留白、非常规取景、环境交代、氛围感都可能是好的；"
    "**不要默认奖励三分法、居中、水平**。\n"
    "点评理由必须基于**真实照片里会出现的东西**（空间层次、环境信息、光线方向、被摄物关系、氛围），"
    "**禁止**基于渲染画质（如「糊/雾/破洞/伪影」）。"
)

SELECT_PROMPT_TMPL = (
    PREAMBLE
    + "\n\n下面是同一场景的 {n} 张候选视点（每张图后紧跟 [候选 名称] 标注）。\n"
    "请选出**在现实中拍摄会最好**的 3 个视点，按优劣排序，并给每个一句点评（说清这个视点好在哪）。\n"
    "只输出 JSON，格式严格如下，不要任何多余文字、不要 markdown 代码块：\n"
    '{{"top3":[{{"name":"候选名","reason":"一句点评"}}]}}\n'
    "候选名必须从这些里选：{names}"
)

# 两段式「全员入围 → 锦标赛」round1 用：从一批候选里选 top-K（K 由调用方指定）
SELECT_BATCH_PROMPT = (
    PREAMBLE
    + "\n\n下面是同一场景的 {n} 张候选视点（每张图后紧跟 [候选 名称] 标注）。\n"
    "请从中选出**在现实中拍摄会最好**的 {k} 个视点，按优劣排序，并给每个一句点评（说清这个视点好在哪）。\n"
    "只输出 JSON，格式严格如下，不要任何多余文字、不要 markdown 代码块：\n"
    '{{"top":[{{"name":"候选名","reason":"一句点评"}}]}}\n'
    "候选名必须从这些里选：{names}"
)

INTENT_PROMPT = (
    PREAMBLE
    + "\n\n看这张候选视点，指出**在现实中拍摄时最需要修正的一个取景问题**，并给出动作。\n"
    "只输出 JSON，格式：{\"issue\":\"一句话\",\"fix\":\"move_subject_left|move_subject_right|"
    "move_subject_up|move_subject_down|enlarge_subject|shrink_subject|none\","
    "\"magnitude\":\"slight|moderate|strong\"}\n"
    "fix=none 表示这个视点已经很好、无需调整。"
)

PAIRWISE_PROMPT = (
    PREAMBLE
    + "\n\n下面是同一场景的**两个**候选视点，按顺序标记为第 1 张、第 2 张。\n"
    "比较两者：在现实中拍摄，哪张会更好？只输出 JSON：{\"better\":\"1\"} 或 {\"better\":\"2\"}。"
)
